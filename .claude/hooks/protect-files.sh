#!/usr/bin/env bash
# PreToolUse(Edit|Write): blocks hand edits of generated EF Core files and secret files.
set -euo pipefail

file=$(jq -r '.tool_input.file_path // ""')
[[ -z "$file" ]] && exit 0

case "$file" in
  */Migrations/*.Designer.cs|*ModelSnapshot.cs)
    echo "Blocked: $file is generated by EF Core. Change the entity/configuration and run 'dotnet ef migrations add' instead." >&2
    exit 2 ;;
  */.env|*/.env.*)
    echo "Blocked: $file holds secrets. Ask the user to edit it; use user-secrets or environment variables for local config." >&2
    exit 2 ;;
esac

exit 0
