using Govern.Application.Common.Abstractions;
using Govern.Domain.Entities;
using Govern.Domain.EntityBase;
using Microsoft.EntityFrameworkCore;

namespace Govern.Infrastructure.Persistence;

/// <summary>
/// EF Core context for PostgreSQL. Tables and columns use snake_case; entity configuration lives in
/// <c>Persistence/Configurations</c>. Created per operation through <see cref="ApplicationDbContextFactory"/>.
/// </summary>
internal sealed class ApplicationDbContext(DbContextOptions<ApplicationDbContext> options) : DbContext(options), IApplicationDbContext
{
    /// <inheritdoc />
    public DbSet<User> Users => Set<User>();

    /// <inheritdoc />
    public DbSet<RefreshToken> RefreshTokens => Set<RefreshToken>();

    /// <inheritdoc />
    public async Task<IApplicationDbContextTransaction> BeginTransactionAsync(CancellationToken cancellationToken) =>
        new ApplicationDbContextTransaction(await Database.BeginTransactionAsync(cancellationToken));

    /// <inheritdoc />
    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.ApplyConfigurationsFromAssembly(typeof(ApplicationDbContext).Assembly);

        foreach (var entityType in modelBuilder.Model.GetEntityTypes().Where(static t => typeof(BaseEntity).IsAssignableFrom(t.ClrType)))
        {
            var entity = modelBuilder.Entity(entityType.ClrType);
            entity.Ignore(nameof(BaseEntity.DomainEvents));

            // Ids are Guid v7 generated by the domain; never by the database. This also makes EF treat new entities
            // reached through navigations (e.g. a new refresh token on a tracked user) as Added.
            entity.Property(nameof(BaseEntity.Id)).ValueGeneratedNever();
        }
    }
}
